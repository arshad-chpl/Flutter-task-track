class Contact {
  final String name;
  final String status;
  final String bio;
  final String phone;
  final String email;
  final String image;
  final String time;

  Contact({
    required this.name,
    required this.status,
    required this.bio,
    required this.phone,
    required this.email,
    required this.image,
    required this.time,
  });
}